#define RANDOM_WALKS_SIMPLEX_BALL_VOLUME_ESTIMATOR_HPP

#include <cstddef>
#include <cmath>
#include <limits>
#include <stdexcept>
#include <vector>
#include <algorithm>

#include <Eigen/Eigen>

